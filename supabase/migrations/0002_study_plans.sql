-- ----------------------------------------------------------------------------
-- table: public.study_plans (safety net for a clean database only)
-- ----------------------------------------------------------------------------
-- По-русски: создаём таблицу только как страховку на случай чистой базы,
-- где её ещё нет. На боевой базе таблица уже существует, поэтому команда
-- просто пропустится. Одна строка = план одного ученика: цель, дата
-- экзамена, сам план (JSON) и служебные даты создания / изменения.
create table if not exists public.study_plans (
  user_id     uuid        primary key references auth.users (id) on delete cascade,
  goal        text,
  exam_date   date,
  plan        jsonb       not null,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

-- ----------------------------------------------------------------------------
-- the fix (the only real schema change in this migration)
-- ----------------------------------------------------------------------------
-- По-русски: разрешаем колонке goal принимать NULL. В мастере плана цель
-- необязательна: когда ученик её не выбрал (в шапке плана видно
-- «Goal: not set»), приложение отправляет в базу goal = null. Колонка
-- с ограничением not null отклоняла такую запись ошибкой 23502
-- (null value in column "goal"), и пользователь видел
-- «Не удалось сохранить план».
-- Команда идемпотентна: если колонка уже допускает NULL, повторный прогон
-- ничего не делает и ничего не ломает.
alter table public.study_plans alter column goal drop not null;

